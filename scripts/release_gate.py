"""Offline, versioned release gate (issue #27).

A release may be tagged only when every check passes:

  version     pyproject.toml, reachweaver/__init__.py and the bundled skill copy agree on X.Y.Z;
              with --tag vX.Y.Z the tag must match that version
  changelog   CHANGELOG.md has a non-empty "## [X.Y.Z]" section (dated YYYY-MM-DD when --tag is given)
  docs        required documents exist and are non-empty, README links the onboarding documents,
              every CLI subcommand is named in README, and relative Markdown links resolve
  bundle      the Claude Code skill runtime is byte-identical to reachweaver/ (run sync_skill.py)
  blockers    every blocked or gated platform has a manual alternative or an explicit marker, and
              the table in docs/TROUBLESHOOTING.md matches reachweaver.onboarding.render_markdown
  readiness   docs/release-readiness.json (the release-readiness scorecard) is valid: known
              statuses, existing evidence paths and test names, every capability-registry platform
              listed, statuses consistent with the registries, and live_receipt_verified only with
              a checked-in first-party receipt file
  tests       python3 -m unittest discover -s tests exits 0 and reports OK

No check uses the network, a credential, the SQLite outbox or git. Exit codes: 0 = all checks
passed; 1 = at least one check failed; 3 = every other check passed but --skip-tests was given,
so the gate is incomplete and must not be used to tag a release.

``--scorecard`` validates and prints only the readiness scorecard (``--json`` for the machine
form); it exits 0 when the file is valid and 1 otherwise.

Usage:  python3 scripts/release_gate.py [--tag vX.Y.Z] [--json] [--skip-tests] [--root DIR]
        python3 scripts/release_gate.py --scorecard [--json] [--root DIR]
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import tomllib
from datetime import date, datetime
from pathlib import Path, PurePosixPath
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
SEMVER = re.compile(r"^\d+\.\d+\.\d+$")
VERSION_LINE = re.compile(r'^__version__\s*=\s*"([^"]+)"\s*$', re.M)
CHANGELOG_HEADING = re.compile(r"^## \[(?P<version>[^\]]+)\](?:\s*-\s*(?P<rest>.*))?$")
ISO_DATE = re.compile(r"^\d{4}-\d{2}-\d{2}\b")
SUBCOMMAND = re.compile(r"""sub\.add_parser\(\s*["']([a-z0-9][a-z0-9-]*)["']""")
MD_LINK = re.compile(r"\]\(([^)\s]+)\)")
BUNDLE = Path(".claude/skills/reachweaver/scripts/reachweaver")
TABLE_BEGIN = "<!-- BEGIN blocker-table: generated by reachweaver.onboarding.render_markdown -->"
TABLE_END = "<!-- END blocker-table -->"

REQUIRED_DOCS = (
    "README.md",
    "CHANGELOG.md",
    "CONTRIBUTING.md",
    "LICENSE",
    "docs/QUICKSTART.md",
    "docs/TROUBLESHOOTING.md",
    "docs/SECURITY-CHECKLIST.md",
    "docs/SECURITY.md",
    "docs/THREAT-MODEL.md",
    "docs/ARCHITECTURE.md",
    "docs/PLATFORMS.md",
    "docs/MANUAL-EXPORT.md",
    "docs/RELEASE-PLAYBOOK.md",
    ".claude/skills/reachweaver/SKILL.md",
)
# Design records kept only in the maintainers' private repository (dual-git setup). They are required
# where they exist, and simply absent in the public tree, so public CI must not demand them.
PRIVATE_ONLY_DOCS = frozenset({"docs/THREAT-MODEL.md"})


def _private_only_and_absent(root: Path, relative: str) -> bool:
    return relative in PRIVATE_ONLY_DOCS and not (root / relative).exists()


README_MUST_LINK = ("docs/QUICKSTART.md", "docs/TROUBLESHOOTING.md", "docs/SECURITY-CHECKLIST.md", "CHANGELOG.md")

# Release-readiness scorecard (issue #27): one row per platform or product area.
READINESS = Path("docs/release-readiness.json")
READINESS_STATUSES = ("not_started", "offline_mock_tested", "manual_export_only", "live_receipt_verified",
                      "blocked")
AREA_KINDS = ("platform", "backend", "area")
BLOCKER_KINDS = ("owner", "live", "policy")
AREA_FIELDS = frozenset({"id", "label", "kind", "status", "issue", "evidence", "blockers"})
AREA_OPTIONAL = frozenset({"capability_id", "distribution_id", "receipt"})
TOP_FIELDS = frozenset({"schema_version", "reviewed_on", "issue", "note", "status_meaning", "areas"})
# Product areas that must stay on the scorecard even though no registry lists them.
REQUIRED_AREAS = ("postiz", "hacker_news", "sources", "content", "scheduler", "analytics", "engagement",
                  "media", "security", "privacy_ops")
AREA_ID = re.compile(r"^[a-z][a-z0-9_]*$")
EVIDENCE_REF = re.compile(r"^(?P<path>[^:\s][^:]*?)(?:::(?P<name>[A-Za-z_][A-Za-z0-9_]*))?$")
RECEIPT_FIELDS = ("area", "remote_url", "observed_at", "source", "first_party")


def _result(name: str, errors: list[str], details: dict | None = None, *, status: str | None = None) -> dict:
    return {"check": name, "status": status or ("pass" if not errors else "fail"),
            "errors": errors, "details": details or {}}


def _init_version(path: Path) -> str | None:
    if not path.is_file():
        return None
    match = VERSION_LINE.search(path.read_text(encoding="utf-8"))
    return match.group(1) if match else None


def project_version(root: Path) -> str | None:
    try:
        data = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError):
        return None
    version = data.get("project", {}).get("version")
    return version if isinstance(version, str) else None


def check_version(root: Path, tag: str | None = None) -> dict:
    errors: list[str] = []
    found = {
        "pyproject.toml": project_version(root),
        "reachweaver/__init__.py": _init_version(root / "reachweaver/__init__.py"),
        str(BUNDLE / "__init__.py"): _init_version(root / BUNDLE / "__init__.py"),
    }
    for where, value in found.items():
        if value is None:
            errors.append(f"{where}: version not found")
    values = {v for v in found.values() if v is not None}
    if len(values) > 1:
        errors.append("versions disagree: " + ", ".join(f"{k}={v}" for k, v in found.items()))
    version = found["pyproject.toml"]
    if version is not None and not SEMVER.match(version):
        errors.append(f"pyproject.toml version {version!r} is not X.Y.Z")
    if tag is not None and version is not None and tag != f"v{version}":
        errors.append(f"tag {tag!r} does not match version v{version}")
    return _result("version", errors, {"version": version, "sources": found, "tag": tag})


def changelog_sections(text: str) -> list[dict]:
    sections: list[dict] = []
    for line in text.splitlines():
        match = CHANGELOG_HEADING.match(line.strip())
        if match:
            sections.append({"version": match.group("version"), "rest": (match.group("rest") or "").strip(),
                             "body": []})
        elif sections and not line.startswith("## "):
            sections[-1]["body"].append(line)
    return sections


def check_changelog(root: Path, version: str | None, *, tagging: bool = False) -> dict:
    path = root / "CHANGELOG.md"
    if not path.is_file():
        return _result("changelog", ["CHANGELOG.md is missing"])
    if version is None:
        return _result("changelog", ["no project version to look up"])
    sections = changelog_sections(path.read_text(encoding="utf-8"))
    matching = [s for s in sections if s["version"] == version]
    errors: list[str] = []
    warnings: list[str] = []
    if not matching:
        errors.append(f"CHANGELOG.md has no '## [{version}]' section")
    elif len(matching) > 1:
        errors.append(f"CHANGELOG.md has {len(matching)} '## [{version}]' sections")
    else:
        section = matching[0]
        if not any(line.strip() for line in section["body"]):
            errors.append(f"CHANGELOG.md section [{version}] is empty")
        dated = bool(ISO_DATE.match(section["rest"]))
        if tagging and not dated:
            errors.append(f"CHANGELOG.md section [{version}] must carry a YYYY-MM-DD release date before tagging")
        elif not dated:
            warnings.append(f"section [{version}] is not dated yet ({section['rest'] or 'no date'}); "
                            f"date it before tagging")
    return _result("changelog", errors, {"version": version, "warnings": warnings})


def cli_subcommands(root: Path) -> list[str]:
    path = root / "reachweaver/cli.py"
    return sorted(set(SUBCOMMAND.findall(path.read_text(encoding="utf-8")))) if path.is_file() else []


def _markdown_files(root: Path) -> list[Path]:
    files = [root / name for name in ("README.md", "CONTRIBUTING.md", "CHANGELOG.md")]
    return [f for f in files if f.is_file()] + sorted((root / "docs").glob("*.md"))


def broken_links(root: Path) -> list[str]:
    """Relative file links that do not resolve. Anchors and bare words like '(urn)' are not checked."""
    problems: list[str] = []
    for path in _markdown_files(root):
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            for target in MD_LINK.findall(line):
                if re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", target) or target.startswith("#"):
                    continue
                file_part = target.split("#", 1)[0]
                if not file_part or ("/" not in file_part and "." not in file_part):
                    continue
                if not (path.parent / file_part).exists():
                    problems.append(f"{path.relative_to(root)}:{number}: broken link {target}")
    return problems


def check_docs(root: Path) -> dict:
    errors: list[str] = []
    for name in REQUIRED_DOCS:
        if _private_only_and_absent(root, name):
            continue
        path = root / name
        if not path.is_file() or not path.read_text(encoding="utf-8").strip():
            errors.append(f"required document missing or empty: {name}")
    readme_path = root / "README.md"
    readme = readme_path.read_text(encoding="utf-8") if readme_path.is_file() else ""
    for target in README_MUST_LINK:
        if f"]({target}" not in readme:
            errors.append(f"README.md does not link {target}")
    commands = cli_subcommands(root)
    if not commands:
        errors.append("no CLI subcommands found in reachweaver/cli.py")
    undocumented = [c for c in commands if not re.search(rf"(?<![\w-]){re.escape(c)}(?![\w-])", readme)]
    errors.extend(f"README.md does not mention CLI subcommand {c!r}" for c in undocumented)
    links = broken_links(root)
    errors.extend(links)
    return _result("docs", errors, {"required": list(REQUIRED_DOCS), "subcommands": len(commands),
                                    "links_checked_files": len(_markdown_files(root))})


def check_bundle(root: Path) -> dict:
    errors: list[str] = []
    source = root / "reachweaver"
    target = root / BUNDLE
    files = sorted([*source.glob("*.py"), *source.glob("*.json")])
    for file in files:
        copy = target / file.name
        if not copy.is_file() or copy.read_bytes() != file.read_bytes():
            errors.append(f"bundled skill copy differs: {BUNDLE / file.name} (run python3 scripts/sync_skill.py)")
    extra = sorted(p.name for p in target.glob("*.py") if not (source / p.name).exists()) if target.is_dir() else []
    errors.extend(f"stale bundled file {BUNDLE / name}" for name in extra)
    return _result("bundle", errors, {"files": len(files)})


def extract_table(text: str) -> str | None:
    start, end = text.find(TABLE_BEGIN), text.find(TABLE_END)
    if start < 0 or end < start:
        return None
    return text[start + len(TABLE_BEGIN):end].strip("\n") + "\n"


def check_blockers(root: Path) -> dict:
    """Import the onboarding audit from ``root`` (stdlib only, no network)."""
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))
    try:
        from reachweaver.onboarding import blocker_audit, render_markdown
    except Exception as exc:  # noqa: BLE001 - report any import failure as a gate failure
        return _result("blockers", [f"cannot import reachweaver.onboarding: {type(exc).__name__}: {exc}"])
    try:
        audit = blocker_audit()
    except Exception as exc:  # noqa: BLE001 - an invalid registry is a gate failure
        return _result("blockers", [f"registry error: {type(exc).__name__}: {exc}"])
    errors = list(audit["errors"])
    doc = root / "docs/TROUBLESHOOTING.md"
    table = extract_table(doc.read_text(encoding="utf-8")) if doc.is_file() else None
    if table is None:
        errors.append("docs/TROUBLESHOOTING.md lacks the generated blocker-table markers")
    elif table != render_markdown(audit):
        errors.append("docs/TROUBLESHOOTING.md blocker table is stale; regenerate it with "
                      "python3 scripts/release_gate.py --print-blocker-table")
    counts: dict[str, int] = {}
    for row in audit["rows"]:
        counts[row["kind"]] = counts.get(row["kind"], 0) + 1
    return _result("blockers", errors, {"rows": len(audit["rows"]), "kinds": counts, "live": audit["live"]})


def _repo_file(root: Path, rel: object) -> tuple[Path | None, str | None]:
    """Resolve a repository-relative POSIX path that must name an existing file inside ``root``."""
    if not isinstance(rel, str) or not rel.strip():
        return None, "must be a non-empty relative path"
    pure = PurePosixPath(rel)
    if pure.is_absolute() or "\\" in rel or ".." in pure.parts or rel != rel.strip():
        return None, f"{rel!r} must be a relative repository path without '..'"
    target = root / rel
    try:
        inside = target.resolve().is_relative_to(root.resolve())
    except OSError:
        inside = False
    if not inside or not target.is_file():
        return None, f"{rel} does not exist"
    return target, None


def _evidence_errors(root: Path, where: str, item: object) -> list[str]:
    """``path`` or ``path.py::Name``; Name must be a class or function defined in that file."""
    if not isinstance(item, str):
        return [f"{where}: evidence entries must be strings"]
    match = EVIDENCE_REF.match(item)
    if not match:
        return [f"{where}: evidence {item!r} is not 'path' or 'path.py::Name'"]
    if _private_only_and_absent(root, match.group("path")):
        return []
    target, problem = _repo_file(root, match.group("path"))
    if problem:
        return [f"{where}: evidence {problem}"]
    name = match.group("name")
    if name is None:
        return []
    assert target is not None
    if target.suffix != ".py":
        return [f"{where}: evidence {item}: '::Name' is only allowed for .py files"]
    pattern = rf"^\s*(?:async\s+def|def|class)\s+{re.escape(name)}\b"
    if not re.search(pattern, target.read_text(encoding="utf-8"), re.M):
        return [f"{where}: evidence {item}: {match.group('path')} defines no class or function {name}"]
    return []


def _receipt_errors(root: Path, where: str, area_id: str, receipt: object) -> list[str]:
    """A live receipt is a checked-in JSON file recorded by the owner from the native platform."""
    target, problem = _repo_file(root, receipt)
    if problem:
        return [f"{where}: live_receipt_verified needs a first-party receipt file; receipt {problem}"]
    assert target is not None
    try:
        data = json.loads(target.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, ValueError):
        return [f"{where}: receipt {receipt} is not valid JSON"]
    if not isinstance(data, dict):
        return [f"{where}: receipt {receipt} must be a JSON object"]
    errors = [f"{where}: receipt {receipt} lacks {field!r}" for field in RECEIPT_FIELDS if field not in data]
    if errors:
        return errors
    if data["area"] != area_id:
        errors.append(f"{where}: receipt {receipt} is for area {data['area']!r}, not {area_id!r}")
    if data["first_party"] is not True:
        errors.append(f"{where}: receipt {receipt} must set first_party: true")
    url = data["remote_url"]
    parts = urlsplit(url) if isinstance(url, str) else None
    if parts is None or parts.scheme != "https" or not parts.hostname or parts.username or parts.password:
        errors.append(f"{where}: receipt {receipt} remote_url must be an https URL without credentials")
    try:
        observed = datetime.fromisoformat(data["observed_at"]) if isinstance(data["observed_at"], str) else None
    except ValueError:
        observed = None
    if observed is None or observed.tzinfo is None:
        errors.append(f"{where}: receipt {receipt} observed_at must be an ISO timestamp with a time zone")
    if not isinstance(data["source"], str) or not data["source"].strip():
        errors.append(f"{where}: receipt {receipt} source must name where the post was observed")
    return errors


def _platform_consistency(where: str, area: dict, capabilities: dict, distribution: dict,
                          alternatives: dict) -> list[str]:
    """Statuses must agree with the capability/distribution registries and onboarding alternatives."""
    errors: list[str] = []
    status = area.get("status")
    cap_id, dist_id = area.get("capability_id"), area.get("distribution_id")
    if area.get("kind") == "platform" and cap_id is None and dist_id is None:
        errors.append(f"{where}: a platform row needs a capability_id or distribution_id")
    if cap_id is not None:
        entry = capabilities.get(cap_id)
        if entry is None:
            errors.append(f"{where}: capability_id {cap_id!r} is not in reachweaver/platform_registry.json")
        else:
            live = entry.get("status") == "supported" and entry.get("reachweaver_adapter") in ("live_text", "live_media")
            kind = alternatives.get(cap_id, (None, ""))[0]
            if status in ("offline_mock_tested", "live_receipt_verified") and not live:
                errors.append(f"{where}: status {status} but the capability registry has no live adapter")
            elif status == "manual_export_only" and (live or kind not in ("manual_export", "draft_export")):
                errors.append(f"{where}: manual_export_only needs a manual_export or draft_export alternative "
                              f"in reachweaver/onboarding.py (found {kind or 'a live adapter'})")
            elif status == "blocked" and (live or not (entry.get("status") == "blocked"
                                                       or kind in ("human_only", "unsupported"))):
                errors.append(f"{where}: blocked but the registry neither blocks it nor marks it human-only")
            elif status == "not_started" and live:
                errors.append(f"{where}: not_started but the capability registry lists a live adapter")
    if dist_id is not None and dist_id not in distribution:
        errors.append(f"{where}: distribution_id {dist_id!r} is not in reachweaver/distribution_registry.json")
    # The human-only rule keys on the row's id and capability_id as well as distribution_id, so deleting
    # distribution_id from the hacker_news or reddit row cannot silently lift the block.
    human_only = [key for key in dict.fromkeys((area.get("id"), cap_id, dist_id))
                  if isinstance(key, str) and distribution.get(key, {}).get("human_only") is True]
    for key in human_only:
        if dist_id != key:
            errors.append(f"{where}: {key} is human-only in the distribution registry, so the row must carry "
                          f"distribution_id {key!r} (found {dist_id!r})")
    if human_only and status != "blocked":
        errors.append(f"{where}: {', '.join(human_only)} is human-only in the distribution registry, so its "
                      f"status must be blocked (found {status})")
    return errors


def _area_errors(root: Path, index: int, area: object) -> list[str]:
    if not isinstance(area, dict):
        return [f"areas[{index}]: must be an object"]
    where = f"areas[{index}] ({area.get('id', '?')})"
    errors: list[str] = []
    missing = sorted(AREA_FIELDS - area.keys())
    unknown = sorted(area.keys() - AREA_FIELDS - AREA_OPTIONAL)
    errors.extend(f"{where}: missing field {name!r}" for name in missing)
    errors.extend(f"{where}: unknown field {name!r}" for name in unknown)
    if not isinstance(area.get("id"), str) or not AREA_ID.match(area["id"]):
        errors.append(f"{where}: id must match {AREA_ID.pattern}")
    if not isinstance(area.get("label"), str) or not area["label"].strip():
        errors.append(f"{where}: label must be a non-empty string")
    if area.get("kind") not in AREA_KINDS:
        errors.append(f"{where}: kind must be one of {', '.join(AREA_KINDS)}")
    status = area.get("status")
    if status not in READINESS_STATUSES:
        errors.append(f"{where}: unknown status {status!r}; use one of {', '.join(READINESS_STATUSES)}")
    issue = area.get("issue")
    if issue is not None and (isinstance(issue, bool) or not isinstance(issue, int) or issue <= 0):
        errors.append(f"{where}: issue must be a positive integer or null")
    evidence = area.get("evidence")
    if not isinstance(evidence, list) or not evidence:
        errors.append(f"{where}: evidence must be a non-empty list of repository paths")
    else:
        for item in evidence:
            errors.extend(_evidence_errors(root, where, item))
    blockers = area.get("blockers")
    if not isinstance(blockers, list):
        errors.append(f"{where}: blockers must be a list")
        blockers = []
    for blocker in blockers:
        if (not isinstance(blocker, dict) or set(blocker) != {"kind", "detail"}
                or blocker["kind"] not in BLOCKER_KINDS
                or not isinstance(blocker["detail"], str) or not blocker["detail"].strip()):
            errors.append(f"{where}: each blocker is {{kind: {'|'.join(BLOCKER_KINDS)}, detail: non-empty}}")
    if status == "live_receipt_verified":
        errors.extend(_receipt_errors(root, where, str(area.get("id")), area.get("receipt")))
    else:
        if "receipt" in area:
            errors.append(f"{where}: receipt is only allowed with status live_receipt_verified")
        if not blockers:
            errors.append(f"{where}: status {status} needs at least one blocker naming what is still missing")
    return errors


def load_registries(root: Path) -> tuple[dict, dict, dict]:
    """Capability and distribution registries from ``root`` plus onboarding alternatives (offline)."""
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))
    from reachweaver.capabilities import load_registry as load_capabilities
    from reachweaver.distribution import load_registry as load_distribution
    from reachweaver.onboarding import CAPABILITY_ALTERNATIVES
    capabilities = load_capabilities(root / "reachweaver/platform_registry.json")
    distribution = load_distribution(root / "reachweaver/distribution_registry.json")
    return ({p["id"]: p for p in capabilities["platforms"]}, {p["id"]: p for p in distribution["platforms"]},
            dict(CAPABILITY_ALTERNATIVES))


def validate_readiness(data: object, root: Path, *, capabilities: dict, distribution: dict,
                       alternatives: dict) -> list[str]:
    """Return every schema, evidence and consistency error in a parsed readiness file."""
    if not isinstance(data, dict) or data.get("schema_version") != 1:
        return ["schema_version must be 1"]
    errors = [f"unknown top-level field {name!r}" for name in sorted(data.keys() - TOP_FIELDS)]
    try:
        date.fromisoformat(data.get("reviewed_on", ""))
    except (TypeError, ValueError):
        errors.append("reviewed_on must be an ISO date YYYY-MM-DD")
    meaning = data.get("status_meaning")
    if not isinstance(meaning, dict) or set(meaning) != set(READINESS_STATUSES):
        errors.append("status_meaning must define exactly: " + ", ".join(READINESS_STATUSES))
    areas = data.get("areas")
    if not isinstance(areas, list) or not areas:
        return errors + ["areas must be a non-empty list"]
    ids: list[str] = []
    for index, area in enumerate(areas):
        errors.extend(_area_errors(root, index, area))
        if isinstance(area, dict):
            ids.append(str(area.get("id")))
            errors.extend(_platform_consistency(f"areas[{index}] ({area.get('id', '?')})", area,
                                                capabilities, distribution, alternatives))
    errors.extend(f"duplicate area id {i!r}" for i in sorted({i for i in ids if ids.count(i) > 1}))
    covered = {a.get("capability_id") for a in areas if isinstance(a, dict)}
    errors.extend(f"capability-registry platform {pid!r} is missing from the scorecard"
                  for pid in sorted(set(capabilities) - covered))
    errors.extend(f"required area {name!r} is missing from the scorecard"
                  for name in REQUIRED_AREAS if name not in ids)
    return errors


def scorecard(root: Path, path: Path = READINESS) -> dict:
    """Load and validate the readiness scorecard; the report never claims more than the file says."""
    target = root / path
    base = {"scorecard": str(path), "reviewed_on": None, "areas": [], "summary": {}, "live_receipts": 0}
    try:
        data = json.loads(target.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return {**base, "overall": "fail", "errors": [f"{path} is missing"]}
    except (OSError, UnicodeDecodeError, ValueError) as exc:
        return {**base, "overall": "fail", "errors": [f"{path} is not valid JSON: {type(exc).__name__}"]}
    try:
        capabilities, distribution, alternatives = load_registries(root)
    except Exception as exc:  # noqa: BLE001 - an unreadable registry is a gate failure
        return {**base, "overall": "fail", "errors": [f"registry error: {type(exc).__name__}: {exc}"]}
    errors = validate_readiness(data, root, capabilities=capabilities, distribution=distribution,
                                alternatives=alternatives)
    areas = [a for a in data.get("areas", []) if isinstance(a, dict)] if isinstance(data, dict) else []
    summary = {status: sum(1 for a in areas if a.get("status") == status) for status in READINESS_STATUSES}
    return {**base, "overall": "fail" if errors else "pass", "errors": errors,
            "reviewed_on": data.get("reviewed_on") if isinstance(data, dict) else None,
            "areas": areas, "summary": summary, "live_receipts": summary["live_receipt_verified"]}


def check_readiness(root: Path) -> dict:
    report = scorecard(root)
    return _result("readiness", report["errors"], {"file": report["scorecard"], "areas": len(report["areas"]),
                                                   "summary": report["summary"],
                                                   "live_receipts": report["live_receipts"]})


def render_scorecard(report: dict) -> str:
    lines = [f"RELEASE READINESS {report['overall'].upper()}: {report['scorecard']} "
             f"(reviewed {report['reviewed_on'] or 'unknown'}, {len(report['areas'])} areas)"]
    rows = [("AREA", "STATUS", "ISSUE", "EVIDENCE", "BLOCKERS")]
    for area in report["areas"]:
        issue = area.get("issue")
        blockers = area.get("blockers") if isinstance(area.get("blockers"), list) else []
        kinds = sorted({b.get("kind", "?") for b in blockers if isinstance(b, dict)})
        evidence = area.get("evidence") if isinstance(area.get("evidence"), list) else []
        rows.append((str(area.get("label", area.get("id", "?"))), str(area.get("status")),
                     f"#{issue}" if isinstance(issue, int) else "-", str(len(evidence)), ", ".join(kinds) or "-"))
    widths = [max(len(row[i]) for row in rows) for i in range(len(rows[0]))]
    lines.extend("  " + "  ".join(cell.ljust(widths[i]) for i, cell in enumerate(row)).rstrip() for row in rows)
    if report["summary"]:
        lines.append("Summary: " + ", ".join(f"{k} {v}" for k, v in report["summary"].items()))
    lines.append(f"Live receipts verified: {report['live_receipts']}."
                 + (" No area claims a live receipt." if report["live_receipts"] == 0 else ""))
    lines.extend(f"  ERROR: {e}" for e in report["errors"])
    lines.append("A status is not permission, consent or proof of delivery.")
    return "\n".join(lines)


def _offline_env() -> dict:
    """Test environment without ReachWeaver credentials or the live opt-in."""
    return {k: v for k, v in os.environ.items() if not k.startswith("REACHWEAVER_")}


def run_tests(root: Path, start_dir: str = "tests", timeout: int = 1800) -> dict:
    command = [sys.executable, "-m", "unittest", "discover", "-s", start_dir]
    try:
        proc = subprocess.run(command, cwd=root, capture_output=True, text=True, env=_offline_env(),
                              timeout=timeout, check=False)
    except subprocess.TimeoutExpired:
        return _result("tests", [f"test suite exceeded {timeout} s"])
    output = proc.stdout + proc.stderr
    ran = re.findall(r"^Ran (\d+) tests? in ", output, re.M)
    final = [line.strip() for line in output.splitlines() if line.strip()][-1:] or [""]
    errors: list[str] = []
    if proc.returncode != 0:
        errors.append(f"unittest exited {proc.returncode}: {final[0]}")
    elif not final[0].startswith("OK"):
        errors.append(f"unittest did not report OK: {final[0]}")
    if not ran or int(ran[-1]) == 0:
        errors.append("no tests ran")
    return _result("tests", errors, {"command": " ".join(command[1:]), "ran": int(ran[-1]) if ran else 0,
                                     "summary": final[0], "exit_code": proc.returncode})


def run_gate(root: Path, *, tag: str | None = None, skip_tests: bool = False) -> dict:
    version = check_version(root, tag)
    results = [
        version,
        check_changelog(root, version["details"]["version"], tagging=tag is not None),
        check_docs(root),
        check_bundle(root),
        check_blockers(root),
        check_readiness(root),
    ]
    if skip_tests:
        results.append(_result("tests", [], {"note": "skipped by --skip-tests"}, status="skipped"))
    elif all(r["status"] == "pass" for r in results):
        results.append(run_tests(root))
    else:
        results.append(_result("tests", [], {"note": "not run: an earlier check failed"}, status="skipped"))
    failed = [r["check"] for r in results if r["status"] == "fail"]
    skipped = [r["check"] for r in results if r["status"] == "skipped"]
    # Tests are skipped without --skip-tests only after another check failed, so "failed" is set.
    overall = "fail" if failed else ("incomplete" if skipped else "pass")
    return {"gate": "reachweaver-release", "version": version["details"]["version"], "tag": tag,
            "overall": overall, "failed": failed, "checks": results,
            "note": "Offline gate: no network, credentials, outbox or publishing. Passing it is not a release."}


def exit_code(report: dict) -> int:
    return {"pass": 0, "incomplete": 3}.get(report["overall"], 1)


def render(report: dict) -> str:
    lines = [f"RELEASE GATE {report['overall'].upper()}: version {report['version']}"
             + (f", tag {report['tag']}" if report["tag"] else "")]
    for result in report["checks"]:
        detail = ""
        if result["check"] == "tests" and "ran" in result["details"]:
            detail = f" ({result['details']['ran']} tests, {result['details']['summary']})"
        elif result["check"] == "readiness" and "areas" in result["details"]:
            detail = (f" ({result['details']['areas']} areas, "
                      f"{result['details']['live_receipts']} live receipts; see --scorecard)")
        elif result["details"].get("note"):
            detail = f" ({result['details']['note']})"
        lines.append(f"  {result['status'].upper():8} {result['check']}{detail}")
        lines.extend(f"    ERROR: {e}" for e in result["errors"])
        lines.extend(f"    WARNING: {w}" for w in result["details"].get("warnings", []))
    lines.append(report["note"])
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Offline ReachWeaver release gate (issue #27)")
    parser.add_argument("--root", type=Path, default=ROOT, help="repository root (default: this checkout)")
    parser.add_argument("--tag", help="the tag about to be created, e.g. v0.2.0; also requires a dated CHANGELOG")
    parser.add_argument("--skip-tests", action="store_true",
                        help="skip the unit-test run; exits 3 (incomplete) at best, never 0")
    parser.add_argument("--json", action="store_true", help="machine-readable report")
    parser.add_argument("--print-blocker-table", action="store_true",
                        help="print the generated blocker table for docs/TROUBLESHOOTING.md and exit")
    parser.add_argument("--scorecard", action="store_true",
                        help=f"validate and print the release-readiness scorecard ({READINESS}) and exit; "
                             "with --json print it as JSON")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    if args.scorecard:
        if args.tag or args.skip_tests or args.print_blocker_table:
            parser.error("--scorecard cannot be combined with --tag, --skip-tests or --print-blocker-table")
        card = scorecard(root)
        print(json.dumps(card, indent=2) if args.json else render_scorecard(card))
        return 0 if card["overall"] == "pass" else 1
    if args.print_blocker_table:
        sys.path.insert(0, str(root))
        from reachweaver.onboarding import blocker_audit, render_markdown
        print(render_markdown(blocker_audit()), end="")
        return 0
    report = run_gate(root, tag=args.tag, skip_tests=args.skip_tests)
    print(json.dumps(report, indent=2) if args.json else render(report))
    return exit_code(report)


if __name__ == "__main__":
    raise SystemExit(main())
